//! `arteries-gen`: emit deterministic Arteries world data for build tooling.

use arteries_core::{
    manifest_line, worldgen_map_line, worldgen_table_for, MAP_COUNT, MAP_H, MAP_W, MAX_SEED,
    WORLDGEN_VERSION,
};
use std::io::Write;
use std::process::ExitCode;

const USAGE: &str = "\
usage: arteries-gen <terrain|worldgen|worldgen-maps> [--seed N | --count N] [--out PATH]

terrain         emit legacy map data (`seed|row;row`) for the frozen H0 oracle
worldgen        emit `app/worldgen_tables.dia` (terrain + feature codes)
worldgen-maps   emit worldgen map data (`seed|row;row`) for the SVG assets
Without `--seed`, emits seeds `0..count` (default: the built-in map count).
`--seed` must be within `0..=MAX_SEED` and is only valid for `terrain`.";

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("arteries-gen: {error}");
            ExitCode::FAILURE
        }
    }
}

fn run() -> Result<(), String> {
    let mut arguments = std::env::args().skip(1);
    let Some(command) = arguments.next() else {
        return Err(format!("missing command\n\n{USAGE}"));
    };
    if !matches!(command.as_str(), "terrain" | "worldgen" | "worldgen-maps") {
        return Err(format!("unknown command {command:?}\n\n{USAGE}"));
    }

    let mut seed: Option<i64> = None;
    let mut count: Option<i64> = None;
    let mut out: Option<std::path::PathBuf> = None;

    while let Some(argument) = arguments.next() {
        match argument.as_str() {
            "--seed" => seed = Some(parse_number("--seed", arguments.next())?),
            "--count" => count = Some(parse_number("--count", arguments.next())?),
            "--out" => {
                let path = arguments
                    .next()
                    .ok_or_else(|| "--out needs a path".to_string())?;
                out = Some(std::path::PathBuf::from(path));
            }
            "--help" | "-h" => {
                println!("{USAGE}");
                return Ok(());
            }
            other => return Err(format!("unknown option {other:?}\n\n{USAGE}")),
        }
    }

    if command == "terrain" {
        emit(&command, terrain_output(seed, count)?, out)
    } else {
        if seed.is_some() {
            return Err(format!("--seed is not valid for {command}"));
        }
        let count = bounded_count(count)?;
        let output = match command.as_str() {
            "worldgen" => worldgen_table(count)?,
            _ => worldgen_maps(count)?,
        };
        emit(&command, output, out)
    }
}

fn terrain_output(seed: Option<i64>, count: Option<i64>) -> Result<String, String> {
    let seeds = match seed {
        Some(seed) => {
            if count.is_some() {
                return Err("--seed and --count are mutually exclusive".into());
            }
            vec![seed]
        }
        None => (0..bounded_count(count)?).collect(),
    };
    let mut output = String::new();
    for seed in seeds {
        if !(0..=MAX_SEED).contains(&seed) {
            return Err(format!("--seed must be within 0..={MAX_SEED}"));
        }
        output.push_str(&manifest_line(seed));
        output.push('\n');
    }
    Ok(output)
}

fn worldgen_maps(count: i64) -> Result<String, String> {
    let width = usize::try_from(MAP_W).map_err(|_| "map width does not fit usize")?;
    let height = usize::try_from(MAP_H).map_err(|_| "map height does not fit usize")?;
    let mut output = String::new();
    for seed in 0..count {
        output.push_str(&worldgen_map_line(seed, width, height)?);
        output.push('\n');
    }
    Ok(output)
}

fn worldgen_table(count: i64) -> Result<String, String> {
    let width = usize::try_from(MAP_W).map_err(|_| "map width does not fit usize")?;
    let height = usize::try_from(MAP_H).map_err(|_| "map height does not fit usize")?;
    let stride = width * height;
    let mut terrain = String::new();
    let mut features = String::new();
    let mut biomes = String::new();
    let mut temperatures = String::new();
    let mut moistures = String::new();
    let mut climates = String::new();
    let mut deposits = String::new();
    for seed in 0..count {
        let tables = worldgen_table_for(seed, width, height)?;
        terrain.push_str(&packed(&tables.terrain));
        features.push_str(&packed(&tables.features));
        biomes.push_str(&packed(&tables.biome));
        temperatures.push_str(&packed(&tables.temperature));
        moistures.push_str(&packed(&tables.moisture));
        climates.push_str(&packed(&tables.climate));
        deposits.push_str(&packed(&tables.deposit));
    }
    let mut output = format!(
        "# Generated by `arteries-gen worldgen` -- do not edit by hand.\n\
         # Worldgen table version {WORLDGEN_VERSION}. Terrain, feature, biome, temperature, moisture, climate, and deposit codes are packed 10x6 strings.\n\n\
         export fn worldgen_table_version() -> Int:\n  {WORLDGEN_VERSION}\n\n",
    );
    write_packed_table(
        &mut output,
        "worldgen_terrain_rows",
        &terrain,
        count,
        stride,
    );
    output.push('\n');
    write_packed_table(
        &mut output,
        "worldgen_feature_rows",
        &features,
        count,
        stride,
    );
    output.push('\n');
    write_packed_table(&mut output, "worldgen_biome_rows", &biomes, count, stride);
    output.push('\n');
    write_packed_table(
        &mut output,
        "worldgen_temperature_rows",
        &temperatures,
        count,
        stride,
    );
    output.push('\n');
    write_packed_table(
        &mut output,
        "worldgen_moisture_rows",
        &moistures,
        count,
        stride,
    );
    output.push('\n');
    write_packed_table(
        &mut output,
        "worldgen_climate_rows",
        &climates,
        count,
        stride,
    );
    output.push('\n');
    write_packed_table(
        &mut output,
        "worldgen_deposit_rows",
        &deposits,
        count,
        stride,
    );
    Ok(output)
}

fn packed(values: &[i64]) -> String {
    values
        .iter()
        .map(|value| char::from_digit(u32::try_from(*value).unwrap_or(0), 10).unwrap_or('0'))
        .collect()
}

fn write_packed_table(output: &mut String, name: &str, packed: &str, count: i64, stride: usize) {
    output.push_str(&format!(
        "export fn {name}(seed: Int) -> Text:\n  let rows = \"{packed}\"\n  match seed >= 0 and seed < {count}:\n    true => text_slice(rows, seed * {stride}, {stride})\n    false => \"\"\n"
    ));
}

fn bounded_count(count: Option<i64>) -> Result<i64, String> {
    let count = count.unwrap_or(MAP_COUNT);
    if !(1..=4096).contains(&count) {
        return Err("--count must be within 1..=4096".into());
    }
    Ok(count)
}

fn emit(command: &str, output: String, out: Option<std::path::PathBuf>) -> Result<(), String> {
    match out {
        Some(path) => std::fs::write(&path, output)
            .map_err(|error| format!("cannot write {}: {error}", path.display())),
        None => std::io::stdout()
            .write_all(output.as_bytes())
            .map_err(|error| format!("cannot write stdout: {error}")),
    }
    .map_err(|error| format!("{command}: {error}"))
}

fn parse_number(option: &str, value: Option<String>) -> Result<i64, String> {
    let value = value.ok_or_else(|| format!("{option} needs a number"))?;
    value
        .parse()
        .map_err(|_| format!("{option} needs a number, got {value:?}"))
}
